// Serialized into the page together with the reactive runtime.
export function createQt() {
  const bindingValues = new WeakMap();
  const clamp = (x) => Math.max(0, Math.min(1, Number(x)));
  function rgba(r, g, b, a = 1) {
    r = clamp(r);
    g = clamp(g);
    b = clamp(b);
    a = clamp(a);
    const max = Math.max(r, g, b),
      min = Math.min(r, g, b),
      d = max - min;
    const hue =
      d === 0
        ? -1
        : (max === r
            ? (g - b) / d + (g < b ? 6 : 0)
            : max === g
              ? (b - r) / d + 2
              : (r - g) / d + 4) / 6;
    const hex = (v) =>
      Math.round(v * 255)
        .toString(16)
        .padStart(2, '0');
    return Object.freeze({
      r,
      g,
      b,
      a,
      hsvSaturation: max === 0 ? 0 : d / max,
      hsvValue: max,
      hsvHue: hue,
      toString() {
        return '#' + (a < 1 ? hex(a) : '') + hex(r) + hex(g) + hex(b);
      },
    });
  }
  function color(value) {
    if (value && typeof value === 'object' && 'r' in value) return value;
    let s = String(value).toLowerCase();
    s =
      {
        black: '#000000',
        white: '#ffffff',
        transparent: '#00000000',
        red: '#ff0000',
        blue: '#0000ff',
        green: '#008000',
      }[s] || s;
    if (/^#[0-9a-f]{3}$/.test(s))
      s = '#' + [...s.slice(1)].map((c) => c + c).join('');
    if (/^#[0-9a-f]{6}$/.test(s))
      return rgba(
        parseInt(s.slice(1, 3), 16) / 255,
        parseInt(s.slice(3, 5), 16) / 255,
        parseInt(s.slice(5, 7), 16) / 255,
      );
    if (/^#[0-9a-f]{8}$/.test(s))
      return rgba(
        parseInt(s.slice(3, 5), 16) / 255,
        parseInt(s.slice(5, 7), 16) / 255,
        parseInt(s.slice(7, 9), 16) / 255,
        parseInt(s.slice(1, 3), 16) / 255,
      );
    throw Error('Unsupported QML color: ' + s);
  }
  const keys = {
    Escape: 0x01000000,
    Tab: 0x01000001,
    Backtab: 0x01000002,
    Backspace: 0x01000003,
    Return: 0x01000004,
    Enter: 0x01000005,
    Insert: 0x01000006,
    Delete: 0x01000007,
    Home: 0x01000010,
    End: 0x01000011,
    Left: 0x01000012,
    Up: 0x01000013,
    Right: 0x01000014,
    Down: 0x01000015,
    PageUp: 0x01000016,
    PageDown: 0x01000017,
    Space: 32,
    AltGr: 0x01001103,
    CapsLock: 0x01000024,
    NumLock: 0x01000025,
    ScrollLock: 0x01000026,
    Menu: 0x01000055,
  };
  Object.assign(keys, {
    Exclam: 33,
    QuoteDbl: 34,
    NumberSign: 35,
    Dollar: 36,
    Percent: 37,
    Ampersand: 38,
    Apostrophe: 39,
    ParenLeft: 40,
    ParenRight: 41,
    Asterisk: 42,
    Plus: 43,
    Comma: 44,
    Minus: 45,
    Period: 46,
    Slash: 47,
    Colon: 58,
    Semicolon: 59,
    Less: 60,
    Equal: 61,
    Greater: 62,
    Question: 63,
    At: 64,
    BracketLeft: 91,
    Backslash: 92,
    BracketRight: 93,
    AsciiCircum: 94,
    Underscore: 95,
    QuoteLeft: 96,
    BraceLeft: 123,
    Bar: 124,
    BraceRight: 125,
    AsciiTilde: 126,
    Shift: 0x01000020,
    Control: 0x01000021,
    Meta: 0x01000022,
    Alt: 0x01000023,
  });
  for (let i = 0; i < 26; i++) keys[String.fromCharCode(65 + i)] = 65 + i;
  for (let i = 0; i < 10; i++) keys[String(i)] = 48 + i;
  for (let i = 1; i <= 35; i++) keys['F' + i] = 0x01000030 + i - 1;
  return {
    ...Object.fromEntries(
      Object.entries(keys).map(([name, value]) => ['Key_' + name, value]),
    ),
    rgba,
    color,
    darker: (v, f = 2) => {
      const c = color(v);
      return rgba(c.r / f, c.g / f, c.b / f, c.a);
    },
    application: { active: true },
    styleHints: {
      wheelScrollLines: 3,
      mouseDoubleClickInterval: 400,
      startDragDistance: 10,
      startDragTime: 500,
    },
    atob,
    alpha: (value, a) => {
      const c = color(value);
      return rgba(c.r, c.g, c.b, a);
    },
    colorEqual: (a, b) => {
      const x = color(a),
        y = color(b);
      return ['r', 'g', 'b', 'a'].every((k) => Math.abs(x[k] - y[k]) < 1 / 255);
    },
    point: (x, y) => ({ x, y }),
    size: (width, height) => ({ width, height }),
    rect: (x, y, width, height) => ({ x, y, width, height }),
    MouseFocusReason: 0,
    TabFocusReason: 1,
    BacktabFocusReason: 2,
    ActiveWindowFocusReason: 3,
    OtherFocusReason: 7,
    Horizontal: 1,
    Vertical: 2,
    SplitHCursor: 12,
    UserRole: 256,
    AlignLeft: 1,
    AlignRight: 2,
    AlignHCenter: 4,
    AlignTop: 32,
    AlignBottom: 64,
    AlignVCenter: 128,
    AlignBaseline: 256,
    AlignCenter: 132,
    LeftToRight: 0,
    RightToLeft: 1,
    CopyAction: 1,
    MoveAction: 2,
    LinkAction: 4,
    IgnoreAction: 0,
    LeftButton: 1,
    RightButton: 2,
    MiddleButton: 4,
    BackButton: 8,
    ForwardButton: 16,
    ArrowCursor: 0,
    IBeamCursor: 4,
    SizeVerCursor: 5,
    SizeHorCursor: 6,
    OpenHandCursor: 17,
    ClosedHandCursor: 18,
    NoButton: 0,
    AllButtons: 0x07ffffff,
    NoModifier: 0,
    NoScrollPhase: 0,
    ScrollBegin: 1,
    ScrollUpdate: 2,
    ScrollEnd: 3,
    ScrollMomentum: 4,
    ShiftModifier: 0x02000000,
    PointingHandCursor: 13,
    ControlModifier: 0x04000000,
    AltModifier: 0x08000000,
    MetaModifier: 0x10000000,
    binding: (fn) => {
      if (typeof fn !== 'function')
        throw Error('Qt.binding expects a function');
      const value = {};
      bindingValues.set(value, fn);
      return value;
    },
    bindingValue: (value) =>
      value && typeof value === 'object' ? bindingValues.get(value) : undefined,
    createComponent: () => {
      throw Error('Qt.createComponent is not implemented');
    },
  };
}
